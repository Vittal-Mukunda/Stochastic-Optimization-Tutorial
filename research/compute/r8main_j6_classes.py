"""J = 6 survivors against the 551 explicit classes: exact pair-level check with c fixed by the class.

For a class T[R] (proof/n51_local/reg11_S2.txt), a placement of the j-shape and of the heavy miss-sets, the pair-level
system reduces to (all reductions are identities proved in research/N52_TIGHT_J_GE_6.md / BRIEF_R8.md):
  * Lemma A: c(u, v) <= 3 whenever u or v has j = 0;
  * for positive u, v: D(u, v) integer with  ceil((45 + c + E)/4) <= D <= floor((min(Ex_u, Ex_v) + 45 + c + E)/4), D >= 12;
  * row sums over V_+:  sum_{v in V_+ - u} D(u, v) = 120 + 5 j_u - tau_u - 12 |V_0|.
(The V_0 rows and the light-count rows are then automatically satisfied.)  Decided exactly by DFS.
Output: research/compute/r8main_j6_classes.json  (list of surviving (class, placement)).
"""
import itertools
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from n52_tight_local import N_R, check_class, parse_class, ROOT  # noqa: E402

LAM = {6: 4, 7: 7, 8: 9, 9: 10, 10: 10, 11: 10}


def cmatrix(out):
    inn = [sum(1 << i for i in range(N_R) if (out[i] >> j) & 1) for j in range(N_R)]
    return [[bin(inn[u] & inn[v]).count('1') if u != v else 0 for v in range(N_R)] for u in range(N_R)]


def feasible_D(pos, lo, hi, rowsum):
    pairs = list(itertools.combinations(range(len(pos)), 2))
    rem = list(rowsum)
    # remaining min/max per vertex for pruning
    def dfs(k):
        if k == len(pairs):
            return all(r == 0 for r in rem)
        i, j = pairs[k]
        # pruning: remaining pairs at i and j
        for d in range(lo[k], hi[k] + 1):
            rem[i] -= d
            rem[j] -= d
            ok = True
            for x in (i, j):
                later = [kk for kk in range(k + 1, len(pairs)) if x in pairs[kk]]
                mn = sum(lo[kk] for kk in later)
                mx = sum(hi[kk] for kk in later)
                if not (mn <= rem[x] <= mx):
                    ok = False
                    break
            if ok and dfs(k + 1):
                return True
            rem[i] += d
            rem[j] += d
        return False
    return dfs(0)


def check(cm, jv, heavy):
    """heavy: list of (e, frozenset M) for e < 6 (the excess-6 vertex contributes nothing)."""
    pos = [u for u in range(N_R) if jv[u] > 0]
    zero = [u for u in range(N_R) if jv[u] == 0]
    for u in zero:
        if max(cm[u][v] for v in range(N_R) if v != u) > 3:
            return False
    Ex = {u: 5 + 10 * jv[u] - sum(LAM[11 - len(M)] for e, M in heavy if u in M) for u in pos}
    tau = {u: sum(e for e, M in heavy if u in M) for u in pos}
    lo, hi = [], []
    for u, v in itertools.combinations(pos, 2):
        c = cm[u][v]
        E = sum(e for e, M in heavy if u in M and v in M)
        a = max(12, -(-(45 + c + E) // 4))
        b = (min(Ex[u], Ex[v]) + 45 + c + E) // 4
        if a > b:
            return False
        lo.append(a)
        hi.append(b)
    rows = [120 + 5 * jv[u] - tau[u] - 12 * len(zero) for u in pos]
    return feasible_D(pos, lo, hi, rows)


def placements(shape, heavy_pattern):
    """All labelled placements: assign shape values to distinct vertices, then heavy miss-sets as images."""
    s = len(shape)
    res = []
    for P in itertools.permutations(range(N_R), s):
        # canonical order inside equal-j blocks to avoid duplicates
        okp = all(not (shape[i] == shape[i + 1] and P[i] > P[i + 1]) for i in range(s - 1))
        if not okp:
            continue
        jv = [0] * N_R
        for i, x in enumerate(P):
            jv[x] = shape[i]
        res.append((P, jv))
    return res


def main():
    pats = json.loads((HERE / 'r8main_j6_patterns.json').read_text())
    lines = (ROOT / 'proof' / 'n51_local' / 'reg11_S2.txt').read_text().split()
    cms = []
    for line in lines:
        out = parse_class(line)
        check_class(out)
        cms.append(cmatrix(out))
    survivors = []
    t0 = time.time()
    for pi, p in enumerate(pats):
        shape = p['shape']
        s = len(shape)
        heavy_abs = [(e, M) for e, M in p['heavy'] if e != 6]
        # heavy miss-sets are given on positions 0..s-1 of the shape; all relabellings of positions with equal j
        # that change the heavy family are generated by permuting positions inside equal-j blocks
        blocks = {}
        for i, val in enumerate(shape):
            blocks.setdefault(val, []).append(i)
        perms = [()]
        for val, idxs in blocks.items():
            perms = [pp + tuple(zip(idxs, q)) for pp in perms for q in itertools.permutations(idxs)]
        fams = set()
        for pp in perms:
            mp = dict(pp)
            fams.add(tuple(sorted((e, tuple(sorted(mp[x] for x in M))) for e, M in heavy_abs)))
        cnt = 0
        for P, jv in placements(shape, None):
            for fam in fams:
                heavy = [(e, frozenset(P[x] for x in M)) for e, M in fam]
                for ci, cm in enumerate(cms):
                    if check(cm, jv, heavy):
                        survivors.append({'pattern': pi, 'class': ci, 'P': list(P),
                                          'heavy': [[e, sorted(M)] for e, M in heavy]})
                        cnt += 1
        print(f'pattern {pi} {shape} {p["heavy"]}: survivors {cnt}  ({time.time() - t0:.0f}s)', flush=True)
    (HERE / 'r8main_j6_classes.json').write_text(json.dumps(survivors))
    print('total survivors', len(survivors))


if __name__ == '__main__':
    main()
